import { expect, test } from '@playwright/test';
import { transport, pocPassword } from './helpers/sharedTransport';
import { mainNavigation } from './navigation';

test.use({ serviceWorkers: 'block', viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true });
test('search and selection panel preserve choices across categories', async ({ page, context }) => {
  await transport().attach(context);
  await page.goto('./');
  await page.getByRole('button', { name: 'Masha', exact: true }).click();
  await page.getByLabel('Password', { exact: true }).fill(pocPassword);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await mainNavigation(page).getByRole('button', { name: 'Shopping', exact: true }).tap();
  await page.getByRole('button', { name: '+ Quick Add Item' }).tap();
  const modal = page.locator('.quick-add');
  const search = modal.getByLabel('Search products');
  const tabs = modal.getByRole('group', { name: 'Quick Add categories' });
  await expect(search).toHaveAttribute('placeholder', 'Search products…');
  expect(await search.evaluate(el => el.getBoundingClientRect().bottom)).toBeLessThanOrEqual(await tabs.evaluate(el => el.getBoundingClientRect().top));
  await modal.locator('.quick-group').getByRole('button', { name: 'Eggs', exact: true }).tap();
  await search.fill('Mozzarella');
  await modal.locator('.quick-search-results').getByRole('button', { name: 'Mozzarella', exact: true }).tap();
  await search.fill('Karotten');
  await modal.locator('.quick-search-results').getByRole('button', { name: 'Carrots', exact: true }).tap();
  await expect(modal.getByRole('button', { name: 'Add 3 items' })).toBeEnabled();
  const heading = modal.getByRole('button', { name: /Selected items \(3\)/ });
  await expect(heading).toHaveAttribute('aria-expanded', 'false');
  await heading.tap();
  const chips = modal.locator('.quick-selected-chips');
  for (const [name, icon] of [['Eggs', 'egg'], ['Mozzarella', 'mozzarella'], ['Carrots', 'carrot']]) await expect(chips.locator('.quick-selected-chip').filter({ hasText: name }).locator(`[data-illustration="${icon}"]`)).toBeVisible();
  await chips.getByRole('button', { name: 'Remove Mozzarella from selected items' }).tap();
  await expect(modal.getByRole('button', { name: 'Add 2 items' })).toBeEnabled();
  await modal.getByRole('button', { name: 'Clear', exact: true }).tap();
  await expect(modal.getByRole('button', { name: 'Add 0 items' })).toBeDisabled();
  await search.clear();
  await modal.locator('.quick-group').getByRole('button', { name: 'Eggs', exact: true }).tap();
  await tabs.getByRole('button', { name: 'Pets' }).tap();
  await modal.getByRole('button', { name: 'Dry food', exact: true }).tap();
  await tabs.getByRole('button', { name: 'Kids' }).tap();
  await modal.getByRole('button', { name: 'Wipes', exact: true }).tap();
  await expect(modal.getByRole('button', { name: 'Add 3 items' })).toBeEnabled();
  await expect(chips).toContainText('Eggs'); await expect(chips).toContainText('Dry food'); await expect(chips).toContainText('Wipes');
  await chips.getByRole('button', { name: 'Remove Dry food from selected items' }).tap();
  await modal.getByRole('button', { name: 'Add 2 items' }).tap();
  await expect(page.locator('.shopping-active-list').first()).toContainText('Eggs');
  await expect(page.locator('.shopping-active-list').first()).toContainText('Wipes');
  await expect(page.locator('.shopping-active-list').first()).not.toContainText('Dry food');
});
