import { test, expect, type Page } from "@playwright/test";
import { closeAddForm, mainNavigation, openShopping, openChildren, openPets } from "./navigation";
import { transport, pocPassword, pocHome, pocMasha } from "./helpers/sharedTransport";

test.use({ serviceWorkers: `block` });
async function login(page: Page, name: `Masha` | `Damian` = `Masha`) {
  await page.goto(`./`);
  await page.getByRole(`button`, { name, exact: true }).click();
  await page.getByLabel(`Password`, { exact: true }).fill(pocPassword);
  await page.getByRole(`button`, { name: `Sign in`, exact: true }).click();
  await expect(page.getByRole(`button`, { name: `Add purchase`, exact: true })).toBeVisible();
  await openChildren(page, true);
  await expect(page.getByLabel(`Child’s name`)).toBeVisible();
}
async function refresh(page: Page) {
  await page.evaluate(() => window.dispatchEvent(new Event(`focus`)));
}

test(`renaming an existing pet preserves its previously typed animal type`, async ({ page, context }) => {
  await transport().attach(context);
  let saved = { id: `10000000-0000-4000-8000-000000000099`, household_id: pocHome, kind: `pet`, name: `Legacy test pet`, animal_type: `Small parrot`, created_by: pocMasha, created_at: new Date().toISOString() };
  await context.route(`**/rest/v1/family_profiles*`, route => {
    if (route.request().method() === `PATCH`) {
      const change = route.request().postDataJSON();
      expect(change.animal_type).toBe(`Small parrot`);
      saved = { ...saved, ...change };
      return route.fulfill({ json: saved });
    }
    return route.fulfill({ json: [saved] });
  });
  await login(page);
  await openPets(page);
  await closeAddForm(page);
  await page.getByRole(`button`, { name: `Open Legacy test pet's profile` }).click();
  await page.getByRole(`button`, { name: `Edit name, type or birthday` }).click();
  await expect(page.getByLabel(`Pet type (optional)`).first()).toHaveValue(`Small parrot`);
  await expect(page.getByLabel(`Birthday`, { exact: true })).toHaveValue(``);
  await page.getByLabel(`Name`, { exact: true }).fill(`Renamed test pet`);
  await page.getByRole(`button`, { name: `Save profile`, exact: true }).click();
  await expect(page.getByRole(`heading`, { name: `Renamed test pet.`, exact: true })).toBeVisible();
  await expect(page.getByText(`Small parrot`, { exact: true })).toBeVisible();
});

test(`two separate phones share children and pets, edits and confirmed removals`, async ({ browser }) => {
  const server = transport();
  const first = await browser.newContext({ serviceWorkers: `block`, viewport: { width: 390, height: 844 } });
  const second = await browser.newContext({ serviceWorkers: `block`, viewport: { width: 390, height: 844 } });
  await server.attach(first);
  await server.attach(second);
  const a = await first.newPage();
  const b = await second.newPage();
  try {
    await login(a);
    await login(b, `Damian`);
    await expect(a.getByRole(`heading`, { name: `No children added yet` })).toBeVisible();
    await expect(a.getByText(/POC test space shared by both test accounts/)).toBeVisible();
    await a.getByLabel(`Child’s name`).fill(`Synthetic child`);
    await a.getByRole(`button`, { name: `Add child to our home` }).click();
    await expect(a.getByRole(`heading`, { name: `Synthetic child`, exact: true })).toBeVisible();
    await refresh(b);
    await expect(b.getByRole(`heading`, { name: `Synthetic child`, exact: true })).toBeVisible();
    await closeAddForm(b);
    await b.getByRole(`button`, { name: `Edit Synthetic child`, exact: true }).click();
    await b.getByLabel(`Name`, { exact: true }).fill(`Synthetic renamed child`);
    await b.getByRole(`button`, { name: `Save changes`, exact: true }).click();
    await expect(b.getByRole(`heading`, { name: `Synthetic renamed child`, exact: true })).toBeVisible();
    await refresh(a);
    await expect(a.getByRole(`heading`, { name: `Synthetic renamed child`, exact: true })).toBeVisible();
    await openPets(a);
    await a.getByRole(`button`, { name: `+ Add Pet` }).click();
    await a.getByLabel(`Name`, { exact: true }).fill(`Synthetic pet`);
    await a.getByLabel(`Pet type (optional)`).selectOption(`Cat`);
    await a.getByRole(`button`, { name: `Add pet`, exact: true }).click();
    await a.getByRole(`button`, { name: `View pets` }).click();
    await openPets(b); await refresh(b);
    await b.getByRole(`button`, { name: `Open Synthetic pet's profile` }).click();
    await b.getByRole(`button`, { name: `Edit name, type or birthday` }).click();
    await expect(b.getByLabel(`Pet type (optional)`)).toHaveValue(`Cat`);
    await b.getByLabel(`Pet type (optional)`).selectOption(`Dog`);
    await b.getByRole(`button`, { name: `Save profile` }).click();
    await refresh(a);
    await a.getByRole(`button`, { name: `Open Synthetic pet's profile` }).click();
    await expect(a.getByText(`Dog`, { exact: true })).toBeVisible();
    a.once(`dialog`, dialog => dialog.dismiss());
    await a.getByRole(`button`, { name: `Remove pet` }).click();
    await expect(a.getByRole(`button`, { name: `Remove pet` })).toBeVisible();
    a.once(`dialog`, dialog => dialog.accept());
    await a.getByRole(`button`, { name: `Remove pet` }).click();
    await expect(a.getByRole(`button`, { name: `Open Synthetic pet's profile` })).toHaveCount(0);
    await refresh(b);
    await a.reload();
    await openChildren(a, true);
    await expect(a.getByRole(`heading`, { name: `Synthetic renamed child`, exact: true })).toBeVisible();
    expect(await a.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  } finally {
    await first.close();
    await second.close();
  }
});

test(`failed saves, offline changes, folders and navigation preserve family drafts and block updates`, async ({ page, context }) => {
  const server = transport();
  await server.attach(context);
  await page.route(`**/version.json*`, (route) => route.fulfill({ json: { commit: `f`.repeat(40) } }));
  await login(page);
  await page.getByLabel(`Child’s name`).fill(`Synthetic unfinished child`);
  await page.getByLabel(`Birthday (optional)`).fill(`2020-02-29`);
  server.failNextFamilySave();
  await page.getByRole(`button`, { name: `Add child to our home` }).click();
  await expect(page.getByRole(`alert`)).toContainText(`couldn’t save`);
  await expect(page.getByLabel(`Child’s name`)).toHaveValue(`Synthetic unfinished child`);
  await expect(page.getByLabel(`Birthday (optional)`)).toHaveValue(`2020-02-29`);
  await expect(page.getByRole(`heading`, { name: `Synthetic unfinished child`, exact: true })).toHaveCount(0);
  await expect(page.getByRole(`button`, { name: `Update`, exact: true })).toBeDisabled();
  await openPets(page);
  await page.getByRole(`button`, { name: `+ Add Pet` }).click();
  await page.getByLabel(`Name`, { exact: true }).fill(`Synthetic unfinished pet`);
  await mainNavigation(page).getByRole(`button`, { name: `Wishlist`, exact: true }).click();
  await expect(page.getByRole(`button`, { name: `Update`, exact: true })).toBeDisabled();
  await openPets(page);
  await page.getByRole(`button`, { name: `+ Add Pet` }).click();
  await expect(page.getByLabel(`Name`, { exact: true })).toHaveValue(`Synthetic unfinished pet`);
  await openChildren(page, true);
  await expect(page.getByLabel(`Child’s name`)).toHaveValue(`Synthetic unfinished child`);
  await context.setOffline(true);
  await expect(page.getByRole(`button`, { name: `Add child to our home` })).toBeDisabled();
  await expect(page.getByText(/You’re offline. Your unfinished text/)).toBeVisible();
  await context.setOffline(false);
  await expect(page.getByLabel(`Child’s name`)).toHaveValue(`Synthetic unfinished child`);
  await page.getByRole(`button`, { name: `Add child to our home` }).click();
  await expect(page.getByRole(`heading`, { name: `Synthetic unfinished child`, exact: true })).toBeVisible();
  await closeAddForm(page);
  await page.getByRole(`button`, { name: `Edit Synthetic unfinished child`, exact: true }).click();
  await page.getByLabel(`Name`, { exact: true }).fill(`Synthetic failed rename`);
  await page.getByLabel(`Birthday (optional)`).first().fill(`2020-03-01`);
  server.failNextFamilySave();
  await page.getByRole(`button`, { name: `Save changes`, exact: true }).click();
  await expect(page.getByRole(`alert`)).toContainText(`couldn’t save`);
  await expect(page.getByLabel(`Name`, { exact: true })).toHaveValue(`Synthetic failed rename`);
  await expect(page.getByLabel(`Birthday (optional)`).first()).toHaveValue(`2020-03-01`);
});

test(`birthdays are shared calendar dates across time zones and can be changed or cleared`, async ({ browser }) => {
  const server = transport();
  const first = await browser.newContext({ serviceWorkers: `block`, viewport: { width: 390, height: 844 }, timezoneId: `Pacific/Honolulu` });
  const second = await browser.newContext({ serviceWorkers: `block`, viewport: { width: 390, height: 844 }, timezoneId: `Pacific/Kiritimati` });
  await server.attach(first);
  await server.attach(second);
  const a = await first.newPage();
  const b = await second.newPage();
  const card = (page: Page, name: string) => page.getByRole(`article`).filter({ has: page.getByRole(`heading`, { name, exact: true }) });
  try {
    await login(a);
    await login(b, `Damian`);
    await a.getByLabel(`Child’s name`).fill(`Birthday test child`);
    await a.getByLabel(`Birthday (optional)`).fill(`2020-02-29`);
    await a.getByRole(`button`, { name: `Add child to our home` }).click();
    await expect(card(a, `Birthday test child`).locator(`time`)).toHaveText(`29 February 2020`);
    await refresh(b);
    await expect(card(b, `Birthday test child`).locator(`time`)).toHaveAttribute(`datetime`, `2020-02-29`);
    await expect(card(b, `Birthday test child`).locator(`time`)).toHaveText(`29 February 2020`);
    await closeAddForm(b);
    await b.getByRole(`button`, { name: `Edit Birthday test child`, exact: true }).click();
    await expect(b.getByLabel(`Birthday (optional)`).first()).toHaveValue(`2020-02-29`);
    await b.getByLabel(`Birthday (optional)`).first().fill(`2020-03-01`);
    await b.getByRole(`button`, { name: `Save changes`, exact: true }).click();
    await expect(card(b, `Birthday test child`).locator(`time`)).toHaveText(`1 March 2020`);
    await a.reload();
    await openChildren(a, true);
    await expect(card(a, `Birthday test child`).locator(`time`)).toHaveText(`1 March 2020`);
    await openPets(a);
    await a.getByRole(`button`, { name: `+ Add Pet` }).click();
    await a.getByLabel(`Name`, { exact: true }).fill(`Birthday test pet`);
    await a.getByLabel(`Pet type (optional)`).selectOption(`Cat`);
    await a.getByLabel(`Birthday (optional)`).fill(`2022-01-01`);
    await a.getByRole(`button`, { name: `Add pet`, exact: true }).click();
    await a.getByRole(`button`, { name: `View pets` }).click();
    await openPets(b); await refresh(b);
    await b.getByRole(`button`, { name: `Open Birthday test pet's profile` }).click();
    await expect(b.getByText(/Birthday: 1 January 2022/)).toBeVisible();
    await b.getByRole(`button`, { name: `Edit name, type or birthday` }).click();
    await b.getByLabel(`Birthday`, { exact: true }).fill(``);
    await b.getByRole(`button`, { name: `Save profile` }).click();
    await expect(b.getByText(/Birthday: 1 January 2022/)).toHaveCount(0);
    expect(await a.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  } finally {
    await first.close();
    await second.close();
  }
});

test(`children and pets show live age, preserving drafts over midnight and after sleep`, async ({ page, context }) => {
  await page.clock.install({ time: new Date(`2024-03-01T23:59:00Z`) });
  await transport().attach(context);
  await login(page);
  const card = (name: string) => page.getByRole(`article`).filter({ has: page.getByRole(`heading`, { name, exact: true }) });
  await page.getByLabel(`Child’s name`).fill(`Age test child`);
  await page.getByLabel(`Birthday (optional)`).fill(`2024-03-01`);
  await page.getByRole(`button`, { name: `Add child to our home` }).click();
  await expect(card(`Age test child`).locator(`.family-age`)).toHaveText(`Born today`);
  await openPets(page);
  await page.getByRole(`button`, { name: `+ Add Pet` }).click();
  await page.getByLabel(`Name`, { exact: true }).fill(`Age test pet`);
  await page.getByLabel(`Pet type (optional)`).selectOption(`Cat`);
  await page.getByLabel(`Birthday (optional)`).fill(`2022-12-31`);
  await page.getByRole(`button`, { name: `Add pet`, exact: true }).click();
  await page.getByRole(`button`, { name: `View pets` }).click();
  await page.getByRole(`button`, { name: `Open Age test pet's profile` }).click();
  await expect(page.getByText(/1 year, 2 months, 1 day old/)).toBeVisible();
  await openChildren(page, true);
  await page.getByLabel(`Child’s name`).fill(`Unfinished age test draft`);
  await page.getByLabel(`Birthday (optional)`).fill(`2021-09-02`);
  await page.clock.fastForward(61_000);
  await expect(card(`Age test child`).locator(`.family-age`)).toHaveText(`1 day old`);
  await expect(page.getByLabel(`Child’s name`)).toHaveValue(`Unfinished age test draft`);
  await expect(page.getByLabel(`Birthday (optional)`)).toHaveValue(`2021-09-02`);
  await page.clock.setSystemTime(new Date(`2024-03-03T12:00:00Z`));
  await refresh(page);
  await expect(card(`Age test child`).locator(`.family-age`)).toHaveText(`2 days old`);
  await expect(page.getByLabel(`Child’s name`)).toHaveValue(`Unfinished age test draft`);
  await openPets(page);
  await page.getByRole(`button`, { name: `Open Age test pet's profile` }).click();
  await expect(page.getByText(/1 year, 2 months, 3 days old/)).toBeVisible();
  await openChildren(page, true);
  await closeAddForm(page);
  await page.getByRole(`button`, { name: `Edit Age test child`, exact: true }).click();
  await page.getByLabel(`Birthday (optional)`).first().fill(`2023-03-03`);
  await page.getByRole(`button`, { name: `Save changes`, exact: true }).click();
  await expect(card(`Age test child`).locator(`.family-age`)).toHaveText(`1 year old`);
  await closeAddForm(page);
  await page.getByRole(`button`, { name: `Edit Age test child`, exact: true }).click();
  await page.getByRole(`article`).filter({ has: page.getByRole(`heading`, { name: `Edit Age test child`, exact: true }) }).getByRole(`button`, { name: `Clear birthday`, exact: true }).click();
  await page.getByRole(`button`, { name: `Save changes`, exact: true }).click();
  await expect(page.getByRole(`button`, { name: `Edit Age test child`, exact: true })).toBeVisible();
  await expect(card(`Age test child`).locator(`.family-age`)).toHaveCount(0);
});

test(`sign-out clears family drafts and a delayed old-household response cannot expose cards to a new account`, async ({ page, context }) => {
  const server = transport();
  await server.attach(context);
  await page.goto(`./`);
  expect(server.familyRequestCount()).toBe(0);
  await login(page);
  await page.getByLabel(`Child’s name`).fill(`Synthetic old home card`);
  await page.getByRole(`button`, { name: `Add child to our home` }).click();
  await expect(page.getByRole(`heading`, { name: `Synthetic old home card`, exact: true })).toBeVisible();
  await page.getByLabel(`Child’s name`).fill(`Synthetic private draft`);
  server.delayFamilyReads();
  const delayedRequest = page.waitForRequest((request) => request.url().includes(`/family_profiles`) && request.method() === `GET`);
  await refresh(page);
  await delayedRequest;
  await openShopping(page);
  page.once(`dialog`, (dialog) => dialog.accept());
  await page.getByRole(`button`, { name: `Sign out`, exact: true }).click();
  await page.getByRole(`button`, { name: `Use a personal email account`, exact: true }).click();
  await page.getByLabel(`Your email`, { exact: true }).fill(`alpha@example.test`);
  await page.getByLabel(`Password`, { exact: true }).fill(`Synthetic-password-only`);
  await page.getByRole(`button`, { name: `Sign in`, exact: true }).click();
  await expect(page.getByRole(`button`, { name: `Create our home`, exact: true })).toBeVisible();
  const requestsBeforeHome = server.familyRequestCount();
  server.releaseFamilyReads();
  await openChildren(page);
  await expect(page.getByRole(`button`, { name: `Connect our home` })).toBeVisible();
  await expect(page.getByText(`Synthetic old home card`, { exact: true })).toHaveCount(0);
  expect(server.familyRequestCount()).toBe(requestsBeforeHome);
  await page.getByRole(`button`, { name: `Connect our home` }).click();
  await page.getByRole(`button`, { name: `Create our home`, exact: true }).click();
  await openChildren(page, true);
  await expect(page.getByLabel(`Child’s name`)).toHaveValue(``);
  await expect(page.getByRole(`heading`, { name: `No children added yet` })).toBeVisible();
});


test(`a delayed save from a previous account cannot add a card or success message to the next home`, async ({ page, context }) => {
  const server = transport();
  await server.attach(context);
  await login(page);
  server.delayFamilyWrites();
  await page.getByLabel(`Child’s name`).fill(`Synthetic delayed card`);
  const saving = page.waitForRequest((request) => request.url().includes(`/family_profiles`) && request.method() === `POST`);
  await page.getByRole(`button`, { name: `Add child to our home` }).click();
  await saving;
  await expect(page.getByRole(`button`, { name: `Saving…` })).toBeDisabled();
  await openShopping(page);
  page.once(`dialog`, (dialog) => dialog.accept());
  await page.getByRole(`button`, { name: `Sign out`, exact: true }).click();
  await page.getByRole(`button`, { name: `Use a personal email account`, exact: true }).click();
  await page.getByLabel(`Your email`, { exact: true }).fill(`alpha@example.test`);
  await page.getByLabel(`Password`, { exact: true }).fill(`Synthetic-password-only`);
  await page.getByRole(`button`, { name: `Sign in`, exact: true }).click();
  await expect(page.getByRole(`button`, { name: `Create our home`, exact: true })).toBeVisible();
  await page.getByRole(`button`, { name: `Create our home`, exact: true }).click();
  await openChildren(page, true);
  const response = page.waitForResponse((value) => value.url().includes(`/family_profiles`) && value.request().method() === `POST`);
  server.releaseFamilyWrites();
  await response;
  await expect(page.getByRole(`heading`, { name: `No children added yet` })).toBeVisible();
  await expect(page.getByText(`Synthetic delayed card`, { exact: true })).toHaveCount(0);
  await expect(page.getByText(`Added to your shared family.`, { exact: true })).toHaveCount(0);
  await expect(page.getByLabel(`Child’s name`)).toHaveValue(``);
});
