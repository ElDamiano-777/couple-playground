import { expect, test } from '@playwright/test';
import { transport, pocPassword } from './helpers/sharedTransport';
import { mainNavigation } from './navigation';

test.use({ serviceWorkers: 'block', viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true });
test('modal keeps favorite and catalog milk separate with compact editable details', async ({ page, context }) => {
  const server = transport();
  server.seedFavorite('Milk', 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO5X0QAAAABJRU5ErkJggg==');
  await server.attach(context);
  await page.goto('./');
  await page.getByRole('button', { name: 'Masha', exact: true }).click();
  await page.getByLabel('Password', { exact: true }).fill(pocPassword);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await mainNavigation(page).getByRole('button', { name: 'Shopping', exact: true }).tap();
  await page.getByRole('button', { name: '+ Quick Add Item' }).tap();
  const modal = page.locator('.quick-add');
  await expect(page.locator('.quick-modal-layer')).toHaveCSS('position', 'fixed');
  expect(await page.evaluate(() => { const nav = document.querySelector('.bottom-nav')!.getBoundingClientRect(); return document.elementFromPoint(nav.x + 20, nav.y + 20)?.closest('.quick-modal-layer') !== null; })).toBe(true);
  const search = modal.getByLabel('Search products');
  await search.fill('mil');
  await modal.locator('.favorite-card').filter({ hasText: 'Milk' }).locator('.favorite-select').tap();
  await modal.locator('.quick-search-results').getByRole('button', { name: 'Milk', exact: true }).tap();
  await expect(modal.getByRole('button', { name: 'Add 2 items' })).toBeEnabled();
  await modal.getByRole('button', { name: /Selected items \(2\)/ }).tap();
  const rows = modal.locator('.quick-review-item');
  await expect(rows).toHaveCount(2);
  await expect(rows.first().getByRole('button', { name: /Milk/ }).first()).toHaveAttribute('aria-expanded', 'false');
  await rows.first().locator('.quick-review-toggle').tap();
  const details = rows.first().getByLabel('Details (optional)');
  await details.fill('Two cartons');
  await rows.first().locator('.quick-review-toggle').tap();
  await rows.first().locator('.quick-review-toggle').tap();
  await expect(rows.first().getByLabel('Details (optional)')).toHaveValue('Two cartons');
  await search.focus(); await modal.locator('.quick-content').dispatchEvent('touchmove');
  await expect(search).not.toBeFocused();
  await modal.getByRole('button', { name: 'Add 2 items' }).tap();
  await expect(page.locator('.quick-modal-layer')).toHaveCount(0);
  await expect(page.locator('.shopping-active-list').first().locator('.shopping-list-row').filter({ hasText: 'Milk' })).toHaveCount(1);
  await expect(page.locator('.shopping-active-list').first()).toContainText('Two cartons');
});
