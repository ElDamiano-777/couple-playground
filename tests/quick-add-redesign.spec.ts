import { expect, test } from '@playwright/test';
import { transport, pocPassword } from './helpers/sharedTransport';
import { mainNavigation } from './navigation';

test.use({ serviceWorkers: 'block', viewport: { width: 320, height: 700 } });
test('Quick Add keeps favorites compact, tabs distinct and selection accessible', async ({ page, context }) => {
  const server = transport();
  const photo = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO5X0QAAAABJRU5ErkJggg==';
  for (const name of ['Favorite milk', 'Favorite tea', 'Favorite bread', 'Favorite with a long product name', 'Favorite rice']) server.seedFavorite(name, photo);
  await server.attach(context); await page.goto('./');
  await page.getByRole('button', { name: 'Masha', exact: true }).click();
  await page.getByLabel('Password', { exact: true }).fill(pocPassword);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await mainNavigation(page).getByRole('button', { name: 'Shopping', exact: true }).click();
  await page.getByRole('button', { name: '+ Quick Add Item' }).click();
  const modal = page.locator('.quick-add'), tabs = page.getByRole('group', { name: 'Quick Add categories' });
  const home = tabs.getByRole('button', { name: 'Home' }), pets = tabs.getByRole('button', { name: 'Pets' }), kids = tabs.getByRole('button', { name: 'Kids' });
  await expect(home).toHaveAttribute('aria-pressed', 'true');
  const colors = await tabs.getByRole('button').evaluateAll(buttons => buttons.map(button => getComputedStyle(button).backgroundColor));
  expect(colors[0]).not.toBe(colors[1]);
  const save = modal.getByRole('button', { name: 'Add 0 items' }); await expect(save).toBeDisabled();
  await expect(save).toHaveCSS('background-color', 'rgb(59, 59, 67)');
  await expect(modal.locator('.favorite-card')).toHaveCount(3);
  await expect(modal.locator('.favorite-card').first().locator('img')).toBeVisible();
  if (process.env.TOGETHER_SCREENSHOTS) { await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve())))); await page.screenshot({ path: `${process.env.TOGETHER_SCREENSHOTS}/quick-add.png`, animations: 'disabled' }); }
  await modal.getByRole('button', { name: 'Show all favorites (5)' }).click();
  await expect(modal.locator('.favorite-card')).toHaveCount(5);
  await modal.getByLabel('Actions for favorite Favorite with a long product name').click();
  await modal.getByRole('button', { name: 'Edit', exact: true }).click();
  await expect(page.getByLabel('Product name')).toHaveValue('Favorite with a long product name');
  page.once('dialog', dialog => dialog.accept()); await modal.getByRole('button', { name: 'Cancel', exact: true }).click();
  await modal.getByRole('button', { name: 'Show less' }).click();
  await page.getByLabel('Search products').fill('favorite rice');
  await expect(modal.locator('.favorite-card')).toHaveCount(1);
  await page.getByLabel('Search products').clear();
  await modal.locator('.favorite-select').filter({ hasText: 'Favorite milk' }).click();
  await expect(modal.getByRole('button', { name: 'Add 1 item', exact: true })).toBeEnabled();
  await modal.locator('.favorite-select').filter({ hasText: 'Favorite milk' }).click();
  await expect(modal.getByRole('button', { name: 'Add 0 items' })).toBeDisabled();
  await modal.getByRole('button', { name: 'Eggs', exact: true }).click();
  await pets.click(); await expect(pets).toHaveAttribute('aria-pressed', 'true');
  await kids.click(); await expect(kids).toHaveAttribute('aria-pressed', 'true');
  await modal.getByRole('button', { name: 'Wipes', exact: true }).click();
  await expect(modal.getByRole('button', { name: 'Add 2 items' })).toHaveCSS('background-color', 'rgb(155, 213, 179)');
  await page.getByLabel('Search products').focus();
  await modal.locator('.quick-content').evaluate(el => { el.scrollTop = el.scrollHeight; });
  const geometry = await page.evaluate(() => { const footer = document.querySelector('.quick-footer')!.getBoundingClientRect(); const nav = document.querySelector('.bottom-nav')!.getBoundingClientRect(); const modal = document.querySelector('.quick-add')!.getBoundingClientRect(); return { footer: footer.bottom, nav: nav.top, left: modal.left, right: modal.right, width: innerWidth }; });
  expect(geometry.footer).toBeLessThanOrEqual(geometry.nav); expect(geometry.left).toBeGreaterThanOrEqual(0); expect(geometry.right).toBeLessThanOrEqual(geometry.width);
  await modal.getByRole('button', { name: 'Add 2 items' }).click();
  await expect(page.locator('.shopping-active-list').first()).toContainText('Eggs');
  await expect(page.locator('.shopping-active-list').first()).toContainText('Wipes');
  await expect(page.locator('.shopping-active-list').first()).not.toContainText('Favorite milk');
  await mainNavigation(page).getByRole('button', { name: 'More', exact: true }).click();
  await page.locator('.more-shortcuts').getByRole('button', { name: 'Settings & notifications' }).click();
  await page.getByLabel('Light', { exact: true }).check();
  await mainNavigation(page).getByRole('button', { name: 'Shopping', exact: true }).click();
  await page.getByRole('button', { name: '+ Quick Add Item' }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await expect(page.locator('.quick-add').getByRole('button', { name: 'Add 0 items' })).toBeDisabled();
  await expect(page.locator('.quick-add .quick-tile').first()).toBeVisible();
  if (process.env.TOGETHER_SCREENSHOTS) { await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve())))); await page.screenshot({ path: `${process.env.TOGETHER_SCREENSHOTS}/quick-add-light.png`, animations: 'disabled' }); }
});
