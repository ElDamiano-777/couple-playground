import { expect, test } from '@playwright/test';
import { transport, pocPassword } from './helpers/sharedTransport';
import { mainNavigation } from './navigation';

test.use({ serviceWorkers: 'block', viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true });
test('Home and Shopping retain actions in compact layouts', async ({ page, context }) => {
  const server = transport();
  server.seedShopping('Cat litter', 'Large pack', false, 'Pets');
  server.seedShopping('Milk with a very long product name that still needs to be readable', 'Brand: Example', false, 'Home');
  server.seedShopping('Wipes', '', false, 'Kids');
  server.seedShopping('Already purchased', '', true, 'Home');
  server.seedTask('Prepare dinner', '2026-03-31', 'high', 'damian');
  const recipe = server.seedRecipe('Pasta night', '200 g pasta', { photo: 'https://example.com/pasta.jpg' });
  server.seedMeal('2026-03-30', 'Dinner', 'Pasta night', recipe);
  await server.attach(context); await page.clock.setFixedTime(new Date('2026-03-30T12:00:00Z'));
  await page.goto('./'); await page.getByRole('button', { name: 'Masha', exact: true }).click();
  await page.getByLabel('Password', { exact: true }).fill(pocPassword); await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.locator('.us-shopping-item')).toHaveCount(3);
  await expect(page.locator('.us-shopping')).not.toContainText('Purchased');
  await expect(page.locator('.dinner-dashboard img')).toHaveAttribute('src', 'https://example.com/pasta.jpg');
  if (process.env.TOGETHER_SCREENSHOTS) await page.screenshot({ path: `${process.env.TOGETHER_SCREENSHOTS}/home-polish.png` });
  await page.locator('.home-shopping-add').tap(); await expect(page.locator('.quick-add')).toBeVisible();
  await page.locator('.quick-add').getByRole('button', { name: 'Close', exact: true }).tap();
  await page.locator('.us-shopping-heading').getByRole('button', { name: 'View all' }).tap();
  const filters = page.getByRole('group', { name: 'Shopping categories' });
  for (const category of ['Home', 'Pets', 'Kids']) await expect(filters.getByRole('button', { name: new RegExp(category) })).toContainText('1');
  await filters.getByRole('button', { name: /Pets/ }).tap();
  await expect(page.locator('.shopping-active-list').first()).toContainText('Cat litter');
  await expect(page.locator('.shopping-active-list').first()).not.toContainText('Wipes');
  await filters.getByRole('button', { name: /Home/ }).tap();
  await expect(page.locator('.shopping-active-list').first()).toContainText('Milk');
  await filters.getByRole('button', { name: /Kids/ }).tap();
  await expect(page.locator('.shopping-active-list').first()).toContainText('Wipes');
  await page.getByLabel('Search shopping list').fill('not on list');
  await expect(page.locator('.shopping-active-list').first()).toContainText('No items match your search.');
  await page.getByLabel('Search shopping list').clear();
  await filters.getByRole('button', { name: /All/ }).tap();
  const purchased = page.locator('.shopping-purchased'); await expect(purchased).not.toHaveAttribute('open', '');
  await purchased.locator('summary').tap(); await expect(purchased).toContainText('Already purchased');
  await expect(page.getByLabel('Mark Cat litter as purchased')).not.toBeChecked();
  await page.locator('.shopping-row-open').filter({ hasText: 'Cat litter' }).tap();
  await expect(page.getByRole('heading', { name: 'Cat litter' })).toBeVisible();
  await page.getByRole('button', { name: 'Close', exact: true }).tap();
  await expect(page.getByLabel('Mark Cat litter as purchased')).not.toBeChecked();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  if (process.env.TOGETHER_SCREENSHOTS) await page.screenshot({ path: `${process.env.TOGETHER_SCREENSHOTS}/shopping-polish.png` });
  await mainNavigation(page).getByRole('button', { name: 'More', exact: true }).tap();
  await page.locator('.more-shortcuts').getByRole('button', { name: 'Settings & notifications' }).tap();
  await page.getByLabel('Light', { exact: true }).check();
  await mainNavigation(page).getByRole('button', { name: 'Shopping', exact: true }).tap();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await expect(page.locator('.shopping-active-list').first()).toContainText('Cat litter');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
