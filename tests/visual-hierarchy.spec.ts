import { expect, test } from '@playwright/test';
import { transport, pocPassword } from './helpers/sharedTransport';
import { mainNavigation } from './navigation';

test.use({ serviceWorkers: 'block', viewport: { width: 390, height: 844 } });
test('shopping content remains prominent in dark and light themes', async ({ page, context }) => {
  const server = transport();
  server.seedShopping('Cat litter', 'Brand: Example · Size: 10 l');
  server.seedTask('Clean kitchen', '2026-11-14', 'high', 'damian');
  server.seedTask('Water plants', '2026-11-15', 'low', 'masha');
  await server.attach(context);
  await page.goto('./');
  await page.getByRole('button', { name: 'Masha', exact: true }).click();
  await page.getByLabel('Password', { exact: true }).fill(pocPassword);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  const card = page.locator('.us-shopping');
  await expect(card.locator('.us-shopping-item')).toHaveCount(1);
  await expect(card.locator('.us-shopping-copy strong')).toHaveCSS('font-size', '18px');
  await expect(card.locator('.us-shopping-copy strong')).toHaveCSS('color', 'rgb(247, 245, 250)');
  expect(await card.evaluate(el => {
    const row = el.querySelector('.us-shopping-list')!.getBoundingClientRect();
    const categories = el.querySelector('.us-shopping-shortcuts')!.getBoundingClientRect();
    return row.top < categories.top;
  })).toBe(true);
  if (process.env.TOGETHER_SCREENSHOTS) await page.screenshot({ path: `${process.env.TOGETHER_SCREENSHOTS}/home.png`, animations: 'disabled' });
  for (const name of ['Eggs', 'Milk', 'A long product name with extra details that should wrap naturally']) server.seedShopping(name, 'Brand: Example · Size: 1 kg');
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect(card.locator('.us-shopping-item')).toHaveCount(3);
  await page.getByRole('button', { name: 'Show all (4)' }).click();
  await expect(card.locator('.us-shopping-item')).toHaveCount(4);
  await card.getByRole('button', { name: 'View all' }).click();
  await page.locator('.shopping-categories').getByRole('button', { name: /^Home/ }).click();
  const product = page.locator('.grocery-row').filter({ hasText: 'A long product name' });
  await expect(product.locator('strong')).toHaveCSS('font-size', '18px');
  expect(await product.locator('strong').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  if (process.env.TOGETHER_SCREENSHOTS) await page.screenshot({ path: `${process.env.TOGETHER_SCREENSHOTS}/shopping.png`, animations: 'disabled' });
  await product.locator('.shopping-item-open').click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(product.getByRole('checkbox')).not.toBeChecked();
  await page.getByRole('dialog').getByRole('button', { name: 'Close' }).click();
  const nav = mainNavigation(page);
  await nav.getByRole('button', { name: 'More', exact: true }).click();
  await page.locator('.more-shortcuts').getByRole('button', { name: 'Settings & notifications' }).click();
  await page.getByLabel('Light', { exact: true }).check();
  await nav.getByRole('button', { name: 'Home', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await expect(card.locator('.us-shopping-copy strong').first()).toHaveCSS('font-size', '18px');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
