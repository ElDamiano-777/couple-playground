import { expect, test } from '@playwright/test';
import { transport, pocPassword } from './helpers/sharedTransport';
import { mainNavigation } from './navigation';

test.use({ serviceWorkers: 'block', viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true });
test('nested products select and add independently of favorites', async ({ page, context }) => {
  await transport().attach(context);
  await page.goto('./');
  await page.getByRole('button', { name: 'Masha', exact: true }).click();
  await page.getByLabel('Password', { exact: true }).fill(pocPassword);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await mainNavigation(page).getByRole('button', { name: 'Shopping', exact: true }).click();
  await page.getByRole('button', { name: '+ Quick Add Item' }).click();
  const modal = page.locator('.quick-add');
  const star = modal.getByRole('button', { name: 'Save Eggs as favorite' });
  await star.tap();
  await expect(modal.getByRole('button', { name: 'Remove Eggs from favorites' })).toHaveAttribute('aria-pressed', 'true');
  await expect(modal.locator('.quick-group').getByRole('button', { name: 'Eggs', exact: true })).toHaveAttribute('aria-pressed', 'false');
  await expect(modal.getByRole('button', { name: 'Add 0 items' })).toBeDisabled();
  page.once('dialog', dialog => dialog.accept());
  await modal.getByRole('button', { name: 'Remove Eggs from favorites' }).tap();
  await expect(modal.getByRole('button', { name: 'Save Eggs as favorite' })).toHaveAttribute('aria-pressed', 'false');
  await modal.locator('.quick-group').getByRole('button', { name: 'Eggs', exact: true }).tap();
  await modal.getByRole('button', { name: 'Rice', exact: true }).tap();
  await modal.getByRole('button', { name: 'Fruit', exact: true }).tap();
  const apples = modal.getByRole('button', { name: 'Apples', exact: true });
  const bananas = modal.getByRole('button', { name: 'Bananas', exact: true });
  await expect(apples).toBeEnabled();
  await expect(apples).toHaveCSS('opacity', '1');
  await expect(apples.locator('svg')).toBeVisible();
  const colors = await apples.locator('..').evaluate(el => ({ background: getComputedStyle(el).backgroundColor, border: getComputedStyle(el).borderWidth, inner: getComputedStyle(el.querySelector('.quick-tile')!).backgroundColor }));
  expect(colors.border).toBe('1px');
  expect(colors.inner).toBe('rgba(0, 0, 0, 0)');
  await apples.tap(); await bananas.tap();
  await expect(modal.getByRole('button', { name: 'Add 4 items' })).toBeEnabled();
  await expect(apples.locator('.quick-check')).toBeVisible();
  await bananas.tap();
  await expect(modal.getByRole('button', { name: 'Add 3 items' })).toBeEnabled();
  await modal.getByRole('button', { name: 'Add 3 items' }).tap();
  await expect(page.locator('.shopping-active-list').first()).toContainText('Apples');
  await expect(page.locator('.shopping-active-list').first()).toContainText('Eggs');
  await expect(page.locator('.shopping-active-list').first()).toContainText('Rice');
  await expect(page.locator('.shopping-active-list').first()).not.toContainText('Bananas');
  await mainNavigation(page).getByRole('button', { name: 'Home', exact: true }).tap();
  await expect(page.locator('main')).toContainText('Apples');
  await mainNavigation(page).getByRole('button', { name: 'Shopping', exact: true }).tap();
  await page.getByRole('button', { name: '+ Quick Add Item' }).tap();
  await modal.getByRole('button', { name: 'Cheese', exact: true }).tap();
  await modal.getByRole('button', { name: 'Gouda', exact: true }).tap();
  await expect(modal.getByRole('button', { name: 'Add 1 item' })).toBeEnabled();
  await modal.getByRole('button', { name: 'Add 1 item' }).tap();
  await expect(page.locator('.shopping-active-list').first()).toContainText('Gouda');
});
