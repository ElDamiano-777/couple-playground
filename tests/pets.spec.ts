import { test, expect } from '@playwright/test';
import { transport, pocPassword } from './helpers/sharedTransport';
import { openPets } from './navigation';

test.use({ serviceWorkers: 'block' });
test('partners share pet details and food', async ({ browser }) => {
  test.setTimeout(120000);
  const server = transport();
  const a = await browser.newContext({ viewport: { width: 320, height: 844 } });
  const b = await browser.newContext({ viewport: { width: 320, height: 844 } });
  await server.attach(a); await server.attach(b);
  const first = await a.newPage(), second = await b.newPage();
  try {
    for (const [page, name] of [[first, 'Masha'], [second, 'Damian']] as const) {
      await page.goto('./'); await page.getByRole('button', { name, exact: true }).click();
      await page.getByLabel('Password', { exact: true }).fill(pocPassword);
      await page.getByRole('button', { name: 'Sign in', exact: true }).click();
      await openPets(page);
    }
    await first.getByRole('button', { name: '+ Add Pet' }).click();
    await first.getByLabel('Name', { exact: true }).fill('Test pet');
    await first.getByLabel('Pet type (optional)').selectOption('Cat');
    await first.getByLabel('Birthday (optional)').fill('2022-01-01');
    await first.getByRole('button', { name: 'Add pet', exact: true }).click();
    await first.getByRole('button', { name: 'View pets' }).click();
    await first.getByRole('button', { name: "Open Test pet's profile" }).click();
    await expect(first.getByLabel('Likes', { exact: true })).toBeHidden();
    await expect(first.getByRole('button', { name: 'Save details' })).toHaveCount(0);
    await expect(first.locator('.pet-feature-food')).toBeVisible();
    await expect(first.locator('.pet-feature-dislikes')).toBeVisible();
    expect(await first.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await first.getByText('Photo and saved notes').click();
    const photo = 'public/icons/icon-192.png';
    await first.getByLabel('Photo', { exact: true }).setInputFiles(photo);
    await expect(first.locator('.pet-profile-photo')).toBeVisible();
    await first.getByLabel('Likes', { exact: true }).fill('Playing');
    await first.getByLabel('Dislikes', { exact: true }).fill('Old dislike note');
    await first.getByLabel('Important Notes', { exact: true }).fill('Old important note');
    await first.getByRole('button', { name: 'Save changes' }).click();
    await first.getByRole('button', { name: 'My Food' }).click();
    await first.getByRole('button', { name: '+ Add Food' }).click();
    const tallImage = await first.evaluate(() => {
      const canvas = document.createElement('canvas');
      canvas.width = 500; canvas.height = 2000;
      const context = canvas.getContext('2d')!;
      context.fillStyle = '#663399'; context.fillRect(0, 0, canvas.width, canvas.height);
      return canvas.toDataURL('image/png').split(',')[1];
    });
    await first.getByLabel('Packaging photo').setInputFiles({ name: 'tall-screenshot.png', mimeType: 'image/png', buffer: Buffer.from(tallImage, 'base64') });
    await expect(first.getByAltText('Food packaging preview')).toBeVisible();
    await first.getByLabel('Name', { exact: true }).fill('Dinner');
    await first.getByLabel('Brand').fill('Example');
    await first.getByLabel('Food type').selectOption('Wet');
    await first.getByLabel('Package size (optional)').fill('1.8 kg');
    await first.getByLabel('Notes (optional)').fill('Serve chilled');
    await first.getByRole('button', { name: 'Save food' }).click();
    await expect(first.getByText('Dinner')).toBeVisible();
    await expect(first.getByText('1.8 kg', { exact: false })).toBeVisible();
    await expect(first.locator('.food-product-photo img')).toHaveCSS('object-fit', 'contain');
    const bounds = await first.locator('.food-product').evaluate(card => {
      const container = card.querySelector('.food-product-photo')!.getBoundingClientRect();
      const image = card.querySelector('img')!.getBoundingClientRect();
      const body = card.querySelector('.food-product-body')!.getBoundingClientRect();
      return { container: { left: container.left, right: container.right, top: container.top, bottom: container.bottom }, image: { left: image.left, right: image.right, top: image.top, bottom: image.bottom }, bodyTop: body.top };
    });
    expect(bounds.image.left).toBeGreaterThanOrEqual(bounds.container.left);
    expect(bounds.image.right).toBeLessThanOrEqual(bounds.container.right);
    expect(bounds.image.top).toBeGreaterThanOrEqual(bounds.container.top);
    expect(bounds.image.bottom).toBeLessThanOrEqual(bounds.container.bottom);
    expect(bounds.bodyTop).toBeGreaterThanOrEqual(bounds.container.bottom);
    await first.locator('.food-product').evaluate(card => card.scrollIntoView({ block: 'start' }));
    const clearOfNavigation = await first.evaluate(() => document.querySelector('.food-product')!.getBoundingClientRect().bottom <= document.querySelector('.bottom-nav')!.getBoundingClientRect().top);
    expect(clearOfNavigation).toBe(true);
    const singleWidth = await first.locator('.food-product').evaluate(el => el.getBoundingClientRect().width);
    const gridWidth = await first.locator('.food-grid').evaluate(el => el.getBoundingClientRect().width);
    expect(Math.abs(singleWidth - gridWidth)).toBeLessThan(2);
    await first.getByRole('button', { name: '+ Add Food' }).click();
    await first.getByLabel('Name', { exact: true }).fill('Second product');
    await first.getByLabel('Packaging photo').setInputFiles({ name: 'second-tall.png', mimeType: 'image/png', buffer: Buffer.from(tallImage, 'base64') });
    await expect(first.getByAltText('Food packaging preview')).toBeVisible();
    await first.getByRole('button', { name: 'Save food' }).click();
    await expect(first.locator('.food-product')).toHaveCount(2);
    const boxes = await first.locator('.food-product').evaluateAll(nodes => nodes.map(node => ({ left: node.getBoundingClientRect().left, top: node.getBoundingClientRect().top })));
    expect(boxes[0].left).toBeLessThan(boxes[1].left);
    expect(boxes[0].top).toBe(boxes[1].top);
    const contained = await first.locator('.food-product-photo').evaluateAll(containers => containers.every(container => {
      const image = container.querySelector('img')!.getBoundingClientRect();
      const bounds = container.getBoundingClientRect();
      return image.left >= bounds.left && image.right <= bounds.right && image.top >= bounds.top && image.bottom <= bounds.bottom;
    }));
    expect(contained).toBe(true);
    await first.getByLabel('Actions for Second product').click();
    first.once('dialog', dialog => dialog.accept());
    await first.getByRole('button', { name: 'Remove Second product' }).click();
    await expect(first.locator('.food-product')).toHaveCount(1);
    await first.getByRole('button', { name: 'Food Preferences', exact: true }).click();
    await first.getByRole('button', { name: '+ Add Dislike' }).click();
    await first.getByLabel('Flavor or ingredient').fill('Chicken');
    await first.getByLabel('Food type').selectOption('Wet');
    await first.getByLabel('Notes (optional)').fill('Prefers fish');
    await first.getByRole('button', { name: 'Save dislike' }).click();
    await expect(first.getByText('Chicken')).toBeVisible();
    await expect(first.getByText('Wet food only')).toBeVisible();
    await first.getByRole('button', { name: '+ Add Like' }).click();
    await first.getByLabel('Flavor or product').fill('Salmon');
    await first.getByRole('button', { name: 'Save like' }).click();
    await first.getByRole('button', { name: '+ Add Note' }).click();
    await first.getByLabel('Note', { exact: true }).fill('Small portions');
    await first.getByRole('button', { name: 'Save note' }).click();
    await second.evaluate(() => window.dispatchEvent(new Event('focus')));
    await expect(second.getByRole('button', { name: "Open Test pet's profile" })).toBeVisible();
    await second.getByRole('button', { name: "Open Test pet's profile" }).click();
    await expect(second.getByLabel('Likes', { exact: true })).toBeHidden();
    await expect(second.locator('.pet-feature-food')).toContainText('Dinner');
    await expect(second.locator('.pet-food-preview img')).toBeVisible();
    await expect(second.locator('.pet-food-preview img')).toHaveCSS('object-fit', 'contain');
    await expect(second.locator('.pet-food-preview')).toContainText('Example');
    await expect(second.locator('.pet-food-preview')).toContainText('1.8 kg');
    const preview = await second.locator('.pet-food-preview').evaluate(row => {
      const image = row.querySelector('.pet-food-thumb')!.getBoundingClientRect();
      const text = row.querySelector('.pet-food-copy')!.getBoundingClientRect();
      return { imageRight: image.right, textLeft: text.left, rowRight: row.getBoundingClientRect().right, textRight: text.right };
    });
    expect(preview.imageRight).toBeLessThan(preview.textLeft);
    expect(preview.textRight).toBeLessThanOrEqual(preview.rowRight);
    await second.getByText('Photo and saved notes').click();
    await expect(second.getByLabel('Likes', { exact: true })).toHaveValue('Playing');
    await expect(second.getByLabel('Dislikes', { exact: true })).toHaveValue('Old dislike note');
    await expect(second.getByLabel('Important Notes', { exact: true })).toHaveValue('Old important note');
    await expect(second.locator('.pet-profile-photo')).toBeVisible();
    await second.locator('.pet-feature-food').click();
    await expect(second.getByText('Dinner')).toBeVisible();
    await expect(second.locator('.food-product-photo img')).toBeVisible();
    await expect(second.getByText('Serve chilled')).toBeVisible();
    await second.getByLabel('Actions for Dinner').click();
    await second.getByRole('button', { name: 'Edit Dinner' }).click();
    await expect(second.getByLabel('Package size (optional)')).toHaveValue('1.8 kg');
    await second.getByLabel('Name', { exact: true }).fill('Updated dinner');
    await second.getByLabel('Food type').selectOption('Dry');
    await second.getByRole('button', { name: 'Save food' }).click();
    await expect(second.getByText('Updated dinner')).toBeVisible();
    await second.getByRole('button', { name: 'Food Preferences', exact: true }).click();
    await expect(second.getByText('Chicken')).toBeVisible();
    await expect(second.getByText('Wet food only')).toBeVisible();
    await expect(second.getByText('Salmon')).toBeVisible();
    await expect(second.getByText('Small portions')).toBeVisible();
    await second.getByRole('button', { name: 'Edit Salmon' }).click();
    await second.getByLabel('Flavor or product').fill('Tuna');
    await second.getByRole('button', { name: 'Save like' }).click();
    await second.getByRole('button', { name: 'Edit Small portions' }).click();
    await second.getByLabel('Note', { exact: true }).fill('Serve small portions');
    await second.getByRole('button', { name: 'Save note' }).click();
    await second.getByRole('button', { name: 'Edit Chicken' }).click();
    await second.getByLabel('Flavor or ingredient').fill('Turkey');
    await second.getByRole('button', { name: 'Save dislike' }).click();
    await expect(second.getByText('Turkey')).toBeVisible();
    await first.evaluate(() => window.dispatchEvent(new Event('focus')));
    await expect(first.getByText('Turkey')).toBeVisible();
    await expect(first.getByText('Tuna')).toBeVisible();
    await expect(first.getByText('Serve small portions')).toBeVisible();
    first.once('dialog', dialog => dialog.accept());
    await first.getByRole('button', { name: 'Remove Tuna' }).click();
    first.once('dialog', dialog => dialog.accept());
    await first.getByRole('button', { name: 'Remove Serve small portions' }).click();
    await first.getByRole('button', { name: '← Pets' }).click();
    await first.getByRole('button', { name: '+ Add Pet' }).click();
    await first.getByLabel('Name', { exact: true }).fill('Another pet');
    await first.getByRole('button', { name: 'Add pet', exact: true }).click();
    await first.getByRole('button', { name: 'View pets' }).click();
    const cards = first.locator('.pet-card');
    await cards.filter({ hasText: 'Another pet' }).getByRole('button', { name: 'My Food' }).click();
    await expect(first.getByText('No food saved yet.')).toBeVisible();
    await first.getByRole('button', { name: 'Food Preferences', exact: true }).click();
    await expect(first.getByText('No food dislikes saved yet.')).toBeVisible();
    await first.getByRole('button', { name: '← Pets' }).click();
    await cards.filter({ hasText: 'Test pet' }).getByRole('button', { name: 'My Food' }).click();
    await first.getByRole('button', { name: 'Food Preferences', exact: true }).click();
    await expect(first.getByText('Turkey')).toBeVisible();
    first.once('dialog', dialog => dialog.accept());
    await first.getByRole('button', { name: 'Remove Turkey' }).click();
    await expect(first.getByText('Turkey')).toHaveCount(0);
    await first.getByRole('button', { name: 'My Food', exact: true }).click();
    await expect(first.getByText('Updated dinner')).toBeVisible();
    first.once('dialog', dialog => dialog.accept());
    await first.getByLabel('Actions for Updated dinner').click();
    await first.getByRole('button', { name: 'Remove Updated dinner' }).click();
    await expect(first.getByText('Updated dinner')).toHaveCount(0);
  } finally { await a.close(); await b.close(); }
});
