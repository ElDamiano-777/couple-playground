import { expect, test } from '@playwright/test';
import { transport, pocPassword } from './helpers/sharedTransport';
import { mainNavigation } from './navigation';

test.use({ serviceWorkers: 'block', viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true });
test('occasion categories keep multi-selection and shared product illustrations', async ({ page, context }) => {
  const server = transport();
  server.seedShopping('Existing bread', '', false, 'Home');
  server.seedFavorite('Saved milk', 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO5X0QAAAABJRU5ErkJggg==');
  await server.attach(context); await page.goto('./');
  await page.getByRole('button', { name: 'Masha', exact: true }).click();
  await page.getByLabel('Password', { exact: true }).fill(pocPassword);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await mainNavigation(page).getByRole('button', { name: 'Shopping', exact: true }).tap();
  await page.locator('.occasion-card').filter({ hasText: 'Party Time' }).tap();
  const panel = page.getByRole('dialog', { name: 'Party Time' });
  await panel.locator('.collection-group-toggle').filter({ hasText: 'Soft Drinks' }).tap();
  await panel.getByRole('button', { name: 'Cola', exact: true }).tap();
  await panel.getByRole('button', { name: 'Sprite', exact: true }).tap();
  if (process.env.OCCASION_PREVIEW_DIR) await page.screenshot({ path: `${process.env.OCCASION_PREVIEW_DIR}/picker.png` });
  await panel.locator('.collection-group-toggle').filter({ hasText: 'Soft Drinks' }).tap();
  await panel.locator('.collection-group-toggle').filter({ hasText: 'Snacks' }).tap();
  await panel.getByRole('button', { name: 'Potato Chips', exact: true }).tap();
  await panel.getByRole('button', { name: 'Nuts', exact: true }).tap();
  await expect(panel.getByRole('button', { name: 'Add 4 items' })).toBeEnabled();
  await panel.locator('.collection-selected-details summary').tap();
  await panel.getByLabel('Details for Cola').fill('Two bottles');
  await panel.getByRole('button', { name: 'Add 4 items' }).tap();
  for (const [name, kind] of [['Cola', 'cola'], ['Sprite', 'sprite'], ['Potato Chips', 'chips'], ['Nuts', 'nuts']]) {
    const row = panel.locator('.occasion-item').filter({ hasText: name });
    await expect(row).toBeVisible(); await expect(row.locator(`[data-illustration="${kind}"]`)).toBeVisible();
    if (name === 'Cola') await expect(row).toContainText('Two bottles');
  }
  await panel.locator('.collection-group-toggle').filter({ hasText: 'Party Supplies' }).tap();
  await panel.getByRole('button', { name: 'Ice', exact: true }).tap();
  await panel.getByRole('button', { name: 'Add 1 item' }).tap();
  await expect(panel.locator('.occasion-item').filter({ hasText: 'Ice' }).locator('[data-illustration="ice"]')).toBeVisible();
  await panel.getByRole('button', { name: 'Close', exact: true }).tap();
  await page.locator('.occasion-card').filter({ hasText: 'Daily Groceries' }).tap();
  const daily = page.getByRole('dialog', { name: 'Daily Groceries' });
  await daily.getByLabel('Search collection products').fill('Mozzarella');
  await daily.getByRole('button', { name: 'Mozzarella', exact: true }).tap();
  await daily.getByRole('button', { name: 'Add 1 item' }).tap();
  await expect(daily.locator('.occasion-item').filter({ hasText: 'Mozzarella' }).locator('[data-illustration="mozzarella"]')).toBeVisible();
  await daily.getByRole('button', { name: 'Close', exact: true }).tap();
  await page.reload(); await mainNavigation(page).getByRole('button', { name: 'Shopping', exact: true }).tap();
  await expect(page.locator('.shopping-active-list').first()).toContainText('Existing bread');
  await page.locator('.occasion-card').filter({ hasText: 'Party Time' }).tap();
  await expect(panel.locator('.occasion-item')).toHaveCount(5);
  await expect(panel.locator('.occasion-item').filter({ hasText: 'Ice' }).locator('[data-illustration="ice"]')).toBeVisible();
  await panel.getByRole('button', { name: 'Close', exact: true }).tap();
  await page.getByRole('button', { name: '+ Quick Add Item' }).tap();
  await expect(page.locator('.favorite-card').filter({ hasText: 'Saved milk' }).locator('img')).toBeVisible();
  await page.locator('.quick-add').getByRole('button', { name: '+ Custom item' }).tap();
  await page.locator('.quick-add').getByLabel('Custom product').fill('Ice');
  await page.locator('.quick-custom').getByRole('button', { name: 'Add', exact: true }).tap();
  await page.locator('.quick-add').getByRole('button', { name: 'Add 1 item' }).tap();
  await expect(page.locator('.shopping-list-row').filter({ hasText: 'Ice' }).locator('[data-illustration="ice"]')).toBeVisible();
  await mainNavigation(page).getByRole('button', { name: 'Home', exact: true }).tap();
  await expect(page.locator('.us-shopping-item').filter({ hasText: 'Ice' }).locator('[data-illustration="ice"]')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
