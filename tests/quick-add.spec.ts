    await a.getByRole('button', { name: 'Carrots', exact: true }).click();
    await expect(a.getByRole('button', { name: 'Carrots', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await a.getByRole('button', { name: 'Carrots', exact: true }).click();
    await a.getByRole('button', { name: 'Cheese', exact: true }).click();
    await expect(a.getByRole('button', { name: 'Gouda', exact: true })).toBeVisible();
    await a.getByRole('button', { name: 'Gouda', exact: true }).click();
    await a.getByRole('button', { name: 'Gouda', exact: true }).click();
    await a.getByRole('button', { name: 'Food', exact: true }).click();
    await expect(a.getByRole('button', { name: 'Food', exact: true })).toHaveAttribute('aria-expanded', 'false');
    await a.getByLabel('Search products').fill('sPoNg');
    await expect(a.getByRole('button', { name: 'Sponges', exact: true })).toBeVisible();
    await a.getByLabel('Search products').fill('nothing matches');
    await expect(a.getByText('No products found. You can add a custom product below.')).toBeVisible();
    await expect(a.getByLabel('Custom product')).toBeVisible();
    await a.getByLabel('Search products').clear();
    await a.getByRole('button', { name: 'Food', exact: true }).click();
    await expect(a.getByRole('button', { name: 'Eggs', exact: true })).toHaveAttribute('aria-pressed', 'true');
    const geometry = async () => a.evaluate(() => {
      const button = document.querySelector('.quick-save')!.getBoundingClientRect();
      const nav = document.querySelector('.bottom-nav')!.getBoundingClientRect();
      const raised = document.querySelector('.bottom-nav .nav-us svg')!.getBoundingClientRect();
      const content = document.querySelector('.quick-content')!.getBoundingClientRect();
      return { top: button.top, bottom: button.bottom, navTop: Math.min(nav.top, raised.top), contentBottom: content.bottom };
    });
    const beforeScroll = await geometry();
    await a.locator('.quick-content').evaluate(element => { element.scrollTop = element.scrollHeight; });
    const afterScroll = await geometry();
    expect(Math.abs(beforeScroll.top - afterScroll.top)).toBeLessThan(1);
    expect(afterScroll.bottom).toBeLessThanOrEqual(afterScroll.navTop);
    expect(afterScroll.contentBottom).toBeLessThanOrEqual(afterScroll.top);
    await a.locator('.quick-selection').filter({ hasText: 'Eggs' }).getByLabel('Details (optional)').fill('12 large');
    await a.getByLabel('Custom product').fill('Special tea');
    await expect(a.getByRole('button', { name: 'Add 2 items' })).toBeDisabled();
    await a.locator('.quick-custom').getByRole('button', { name: 'Add', exact: true }).click();
    await a.locator('.quick-selection').filter({ hasText: 'Special tea' }).getByLabel('Details (optional)').fill('Mint, 2 boxes');
    expect(await a.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect(await a.locator('.quick-content').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
    await a.getByRole('button', { name: 'Add 3 items' }).click();
    await expect(a.locator('.grocery-row').filter({ hasText: 'Eggs' })).toBeVisible();
    await expect(a.locator('.grocery-row').filter({ hasText: 'Eggs' }).locator('.shopping-thumb img')).toHaveCount(0);
    await expect(a.locator('.grocery-row').filter({ hasText: 'Eggs' }).locator('.shopping-thumb')).toBeVisible();
    await expect(a.getByText('12 large')).toBeVisible();
    await b.getByRole('button', { name: 'Refresh', exact: true }).click();
    await expect(b.getByText('Mint, 2 boxes')).toBeVisible();
    await b.getByRole('button', { name: 'Edit Eggs' }).click();
    await b.getByLabel('Details (optional)').fill('6 medium');
    await b.getByRole('button', { name: 'Save item' }).click();
    await a.getByRole('button', { name: 'Refresh', exact: true }).click();
    await expect(a.getByText('6 medium')).toBeVisible();
    await b.getByRole('checkbox', { name: /Eggs/ }).click();
    await expect(b.getByRole('checkbox', { name: /Eggs/ })).toBeChecked();
    await a.getByRole('button', { name: 'Refresh', exact: true }).click();
    await expect(a.getByRole('checkbox', { name: /Eggs/ })).toBeChecked();
    await expect(a.locator('.grocery-row').last()).toContainText('Eggs');
    await expect(a.locator('.grocery-row').last().locator('strong')).toHaveCSS('text-decoration-line', 'line-through');
    await b.getByRole('checkbox', { name: /Eggs/ }).click();
    await expect(b.getByRole('checkbox', { name: /Eggs/ })).not.toBeChecked();
    await a.getByRole('button', { name: 'Refresh', exact: true }).click();
    await expect(a.getByRole('checkbox', { name: /Eggs/ })).not.toBeChecked();
    await expect(a.locator('.grocery-row').first()).toContainText('Eggs');
    b.once('dialog', dialog => dialog.accept());
    await b.getByRole('button', { name: 'Remove Special tea' }).click();
    await a.getByRole('button', { name: 'Refresh', exact: true }).click();
    await expect(a.getByText('Special tea')).toHaveCount(0);
    await a.getByRole('button', { name: '← Shopping' }).click();
    await openShoppingCategory(a, 'Pets');
    await a.getByRole('button', { name: '✦ Quick Add' }).click();
