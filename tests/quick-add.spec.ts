import { expect, test, type Page } from '@playwright/test';
import { transport, pocPassword } from './helpers/sharedTransport';
import { openShoppingCategory } from './navigation';

test.use({ serviceWorkers: 'block' });
async function login(page: Page, name: 'Masha' | 'Damian') {
  await page.goto('./');
  await page.getByRole('button', { name, exact: true }).click();
  await page.getByLabel('Password', { exact: true }).fill(pocPassword);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await openShoppingCategory(page, 'Home');
}
test('Quick Add shares selected and custom items with editable details', async ({ browser }) => {
  test.setTimeout(150000);
  const server = transport();
  const first = await browser.newContext({ viewport: { width: 320, height: 844 }, serviceWorkers: 'block' });
  const second = await browser.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
  await server.attach(first); await server.attach(second);
  const a = await first.newPage(); const b = await second.newPage();
  try {
    await login(a, 'Masha'); await login(b, 'Damian');
    await a.getByRole('button', { name: '✦ Quick Add' }).click();
    await a.getByRole('button', { name: 'Eggs', exact: true }).click();
    await a.getByRole('button', { name: 'Milk', exact: true }).click();
    await a.locator('.quick-selection').filter({ hasText: 'Eggs' }).getByLabel('Details (optional)').fill('12 large');
    await a.getByLabel('Custom product').fill('Special tea');
    await expect(a.getByRole('button', { name: 'Add 2 items' })).toBeDisabled();
    await a.locator('.quick-custom').getByRole('button', { name: 'Add', exact: true }).click();
    await a.locator('.quick-selection').filter({ hasText: 'Special tea' }).getByLabel('Details (optional)').fill('Mint, 2 boxes');
    expect(await a.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await a.getByRole('button', { name: 'Add 3 items' }).click();
    await expect(a.getByText('Eggs', { exact: true })).toBeVisible();
    await expect(a.getByText('12 large')).toBeVisible();
    await b.getByRole('button', { name: 'Refresh', exact: true }).click();
    await expect(b.getByText('Mint, 2 boxes')).toBeVisible();
    await b.getByRole('button', { name: 'Edit Eggs' }).click();
    await b.getByLabel('Details (optional)').fill('6 medium');
    await b.getByRole('button', { name: 'Save item' }).click();
    await a.getByRole('button', { name: 'Refresh', exact: true }).click();
    await expect(a.getByText('6 medium')).toBeVisible();
    await b.getByRole('checkbox', { name: /Eggs/ }).click();
    await expect(b.getByRole('checkbox', { name: /Eggs/ })).toBeChecked();
    await a.getByRole('button', { name: 'Refresh', exact: true }).click();
    await expect(a.getByRole('checkbox', { name: /Eggs/ })).toBeChecked();
    b.once('dialog', dialog => dialog.accept());
    await b.getByRole('button', { name: 'Remove Special tea' }).click();
    await a.getByRole('button', { name: 'Refresh', exact: true }).click();
    await expect(a.getByText('Special tea')).toHaveCount(0);
    await a.getByRole('button', { name: '← Shopping' }).click();
    await openShoppingCategory(a, 'Pets');
    await a.getByRole('button', { name: '✦ Quick Add' }).click();
    await expect(a.getByRole('button', { name: 'Cat litter' })).toBeVisible();
    await a.getByRole('button', { name: 'Cat litter' }).click();
    await a.getByRole('button', { name: 'Add 1 item' }).click();
    await expect(a.getByText('Cat litter', { exact: true })).toBeVisible();
    await b.getByRole('button', { name: '← Shopping' }).click();
    await openShoppingCategory(b, 'Pets');
    await b.getByRole('button', { name: 'Refresh', exact: true }).click();
    await expect(b.getByText('Cat litter', { exact: true })).toBeVisible();
    await a.getByRole('button', { name: '✦ Quick Add' }).click();
    await a.getByRole('button', { name: 'Wet food', exact: true }).click();
    await a.getByRole('button', { name: 'Close', exact: true }).click();
    await a.getByRole('button', { name: '← Shopping' }).click();
    await openShoppingCategory(a, 'Kids');
    await a.getByRole('button', { name: '✦ Quick Add' }).click();
    await expect(a.getByRole('button', { name: 'Diapers' })).toBeVisible();
    await a.getByRole('button', { name: 'Diapers' }).click();
    await a.getByRole('button', { name: 'Wipes' }).click();
    await a.getByRole('button', { name: 'Add 2 items' }).click();
    await expect(a.getByText('Diapers', { exact: true })).toBeVisible();
    await b.getByRole('button', { name: '← Shopping' }).click();
    await openShoppingCategory(b, 'Kids');
    await b.getByRole('button', { name: 'Refresh', exact: true }).click();
    await expect(b.getByText('Wipes', { exact: true })).toBeVisible();
    await a.getByRole('button', { name: '← Shopping' }).click();
    await openShoppingCategory(a, 'Pets');
    await a.getByRole('button', { name: '✦ Quick Add' }).click();
    await expect(a.getByRole('button', { name: 'Wet food', exact: true })).toHaveAttribute('aria-pressed', 'true');
    server.failNextSave();
    await a.getByRole('button', { name: 'Add 1 item' }).click();
    await expect(a.getByRole('alert')).toContainText('couldn’t complete');
    await expect(a.getByRole('button', { name: 'Wet food', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await a.getByRole('button', { name: 'Close', exact: true }).click();
    a.once('dialog', dialog => dialog.accept());
    await a.getByRole('button', { name: 'Sign out', exact: true }).click();
    await a.getByLabel('Password', { exact: true }).fill(pocPassword);
    await a.getByRole('button', { name: 'Sign in', exact: true }).click();
    await openShoppingCategory(a, 'Pets');
    await a.getByRole('button', { name: '✦ Quick Add' }).click();
    await expect(a.getByRole('button', { name: 'Wet food', exact: true })).toHaveAttribute('aria-pressed', 'false');
  } finally { await first.close(); await second.close(); }
});
