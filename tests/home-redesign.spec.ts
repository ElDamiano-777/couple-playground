import { expect, test } from '@playwright/test';
import { transport, pocPassword } from './helpers/sharedTransport';
import { mainNavigation } from './navigation';

test.use({ serviceWorkers: 'block' });
test('Home keeps shared actions and details in a compact phone layout', async ({ page, context }) => {
  const server = transport();
  for (const name of ['Milk', 'Eggs', 'Bread', 'Rice']) server.seedShopping(name, 'Brand: Example · Quantity: 1');
  server.seedTask('Prepare dinner', '2026-03-31', 'high', 'damian');
  const recipe = server.seedRecipe('Pasta night', '200 g pasta', { instructions: 'Cook pasta.', photo: 'https://example.com/pasta.jpg' });
  server.seedMeal('2026-03-30', 'Dinner', 'Pasta night', recipe);
  await server.attach(context);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.clock.setFixedTime(new Date('2026-03-30T12:00:00Z'));
  await page.goto('./');
  await page.getByRole('button', { name: 'Masha', exact: true }).click();
  await page.getByLabel('Password', { exact: true }).fill(pocPassword);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  const sections = page.locator('.dashboard-sections > *');
  await expect(sections).toHaveCount(4);
  await expect(sections.nth(0)).toContainText('Prepare dinner');
  await expect(sections.nth(0)).toContainText('Damian');
  await expect(sections.nth(1)).toContainText('Shared Shopping');
  await expect(sections.nth(2)).toContainText('Quick actions');
  await expect(sections.nth(3)).toContainText('Tonight’s dinner');
  await expect(sections.nth(1)).toContainText('4 items to buy');
  await expect(page.locator('.us-shopping-item')).toHaveCount(3);
  await page.getByRole('button', { name: 'Show all (4)' }).click();
  await expect(page.locator('.us-shopping-item')).toHaveCount(4);
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight));
  const layout = await page.evaluate(() => ({ dinner: document.querySelector('.dinner-dashboard')!.getBoundingClientRect().bottom, nav: document.querySelector('.bottom-nav')!.getBoundingClientRect().top, overflow: document.documentElement.scrollWidth > innerWidth }));
  expect(layout.overflow).toBe(false);
  expect(layout.dinner).toBeLessThanOrEqual(layout.nav);
  await page.locator('.us-shopping-open').filter({ hasText: 'Milk' }).click();
  await expect(page.getByRole('heading', { name: 'Milk' })).toBeVisible();
  await expect(page.getByLabel('Mark Milk as purchased')).not.toBeChecked();
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByLabel('Mark Milk as purchased').click();
  await expect(page.locator('.shopping-count')).toHaveText('3 items to buy');
  await expect(sections.nth(3).locator('img')).toHaveAttribute('src', 'https://example.com/pasta.jpg');
  await sections.nth(3).click();
  await expect(page.locator('.recipe-detail')).toContainText('Cook pasta.');
  const nav = mainNavigation(page);
  await nav.getByRole('button', { name: 'Home', exact: true }).click();
  await page.getByRole('button', { name: 'Love Note', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Love Notes.' })).toBeVisible();
  await page.getByRole('button', { name: '← Home', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Home.' })).toBeVisible();
  await sections.nth(1).getByRole('button', { name: 'View all' }).click();
  await expect(page.getByRole('heading', { name: 'Shopping.' })).toBeVisible();
  await nav.getByRole('button', { name: 'Home', exact: true }).click();
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight));
  const bounds = await page.evaluate(() => ({ actions: document.querySelector('.home-quick-actions')!.getBoundingClientRect().bottom, nav: document.querySelector('.bottom-nav')!.getBoundingClientRect().top, overflow: document.documentElement.scrollWidth > innerWidth }));
  expect(bounds.overflow).toBe(false);
  expect(bounds.actions).toBeLessThanOrEqual(bounds.nav);
  await nav.getByRole('button', { name: 'More', exact: true }).click();
  await page.locator('.more-shortcuts').getByRole('button', { name: 'Settings & notifications' }).click();
  await page.getByLabel('Light', { exact: true }).check();
  await nav.getByRole('button', { name: 'Home', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await expect(page.locator('.task-dashboard')).toContainText('Prepare dinner');
});
