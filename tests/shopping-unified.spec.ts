import { expect, test, type Page } from '@playwright/test';
import { transport, pocPassword } from './helpers/sharedTransport';
import { mainNavigation } from './navigation';

test.use({ serviceWorkers: 'block' });
async function login(page: Page, name: 'Masha' | 'Damian') {
  await page.goto('./'); await page.getByRole('button', { name, exact: true }).click();
  await page.getByLabel('Password', { exact: true }).fill(pocPassword);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
}
test('unified shopping filters, edits and shares purchases across phones', async ({ browser }) => {
  const server = transport(); server.seedShopping('Oat milk', 'Brand: Example · Size: 1 l');
  server.seedShopping('Cat litter', 'Size: 10 l', false, 'Pets'); server.seedShopping('Wipes', '', false, 'Kids');
  server.seedShopping('Purchased tea', '', true, 'Home');
  const a = await browser.newContext({ viewport: { width: 320, height: 844 }, serviceWorkers: 'block' });
  const b = await browser.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
  await server.attach(a); await server.attach(b); const first = await a.newPage(), second = await b.newPage();
  try {
    await login(first, 'Masha'); await login(second, 'Damian');
    await mainNavigation(first).getByRole('button', { name: 'Shopping', exact: true }).click();
    const filters = first.getByRole('group', { name: 'Shopping categories' });
    await expect(filters.getByRole('button', { name: 'All 3' })).toHaveAttribute('aria-pressed', 'true');
    await expect(first.locator('.shopping-active-list').first().locator('.shopping-list-row')).toHaveCount(3);
    await expect(first.locator('.shopping-purchased')).not.toHaveAttribute('open');
    await filters.getByRole('button', { name: 'Pets 1' }).click();
    await expect(first.locator('.shopping-active-list').first()).toContainText('Cat litter');
    await expect(first.locator('.shopping-active-list').first()).not.toContainText('Oat milk');
    await first.getByText('Pet Essentials', { exact: true }).click();
    await expect(first.getByRole('heading', { name: 'Our Pets’ Food' })).toBeVisible();
    await filters.getByRole('button', { name: 'All 3' }).click();
    await first.getByLabel('Search shopping list').fill('oat');
    await expect(first.locator('.shopping-active-list').first().locator('.shopping-list-row')).toHaveCount(1);
    await first.getByLabel('Search shopping list').clear();
    await first.locator('.shopping-row-open').filter({ hasText: 'Oat milk' }).click();
    await expect(first.getByRole('checkbox', { name: 'Mark Oat milk as purchased' })).not.toBeChecked();
    await first.getByRole('dialog').getByRole('button', { name: 'Edit item' }).click();
    await first.getByLabel('Item name').fill('Oat drink');
    await first.getByRole('button', { name: 'Save item' }).click();
    await expect(first.locator('.shopping-active-list').first()).toContainText('Oat drink');
    await first.getByRole('checkbox', { name: 'Mark Oat drink as purchased' }).click();
    await expect(first.locator('.shopping-purchased')).not.toHaveAttribute('open');
    await first.locator('.shopping-purchased summary').click();
    await first.getByRole('checkbox', { name: 'Return Oat drink to active list' }).click();
    await expect(first.getByRole('checkbox', { name: 'Mark Oat drink as purchased' })).toBeVisible();
    await first.locator('.shopping-row-open').filter({ hasText: 'Oat drink' }).click();
    first.once('dialog', dialog => dialog.accept());
    await first.getByRole('dialog').getByRole('button', { name: 'Delete item' }).click();
    await expect(first.locator('.shopping-active-list').first()).not.toContainText('Oat drink');
    await second.evaluate(() => window.dispatchEvent(new Event('focus')));
    await expect(second.locator('.us-shopping')).toContainText('Cat litter');
    await expect(second.locator('.us-shopping')).not.toContainText('Oat drink');
    expect(await first.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    if (process.env.TOGETHER_SCREENSHOTS) await first.screenshot({ path: `${process.env.TOGETHER_SCREENSHOTS}/shopping-unified.png`, animations: 'disabled' });
  } finally { await a.close(); await b.close(); }
});
