import { expect, test } from '@playwright/test';
import { mainNavigation } from './navigation';
import { pocPassword, transport } from './helpers/sharedTransport';

test.use({ serviceWorkers: 'block' });

test('compact home opens task details and reuses all three shared forms on phone screens', async ({ browser }) => {
  for (const viewport of [{ width: 320, height: 700 }, { width: 390, height: 844 }]) {
    const server = transport();
    server.seedTask('Past task', '2026-03-28', 'low', 'damian');
    server.seedTask('Next task', '2026-03-31', 'normal', 'both');
    server.seedTask('Later urgent', '2026-04-02', 'high', 'masha');
    server.seedTask('Completed task', '2026-03-20', 'high', 'masha', '2026-03-29T10:00:00Z');
    server.seedRecipe('Dinner pasta', '200 g pasta', { instructions: 'Cook pasta.' });
    const context = await browser.newContext({ viewport, locale: 'de-DE', timezoneId: 'Europe/Berlin', serviceWorkers: 'block' });
    await server.attach(context); const page = await context.newPage();
    await page.clock.setFixedTime(new Date('2026-03-30T12:00:00Z'));
    await page.goto('./'); await page.getByRole('button', { name: 'Masha', exact: true }).click();
    await page.getByLabel('Password', { exact: true }).fill(pocPassword); await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await mainNavigation(page).getByRole('button', { name: 'Home', exact: true }).click();
    await expect(page.getByText('Everything important, all in one place.')).toBeVisible();
    await expect(page.getByText('Little things bring us closer.')).toHaveCount(0);
    const sections = page.locator('.dashboard-sections > *');
    await expect(sections).toHaveCount(4);
    await expect(sections.nth(0)).toContainText('Upcoming tasks');
    await expect(sections.nth(1)).toContainText('Shopping');
    await expect(sections.nth(2)).toContainText('Quick actions');
    await expect(sections.nth(3)).toContainText('Tonight’s dinner');
    const tasks = page.locator('.home-task');
    await expect(tasks).toHaveCount(2);
    await expect(tasks.nth(0)).toContainText('Past task');
    await expect(tasks.nth(0)).toContainText('Overdue');
    await expect(tasks.nth(1)).toContainText('Next task');
    await expect(tasks.nth(1).locator('.task-badge')).toHaveCount(3);
    await tasks.first().click();
    await expect(page.getByRole('dialog', { name: 'Edit task' }).getByLabel('Task', { exact: true })).toHaveValue('Past task');
    await page.getByRole('dialog', { name: 'Edit task' }).getByRole('button', { name: 'Close' }).click();
    await expect(page.getByLabel('Complete Past task')).toBeVisible();
    await mainNavigation(page).getByRole('button', { name: 'Home', exact: true }).click();
    await page.locator('.task-dashboard').getByRole('button', { name: 'View all' }).click();
    await expect(page.getByLabel('Complete Later urgent')).toBeVisible();
    await mainNavigation(page).getByRole('button', { name: 'Home', exact: true }).click();
    await page.getByRole('button', { name: 'Add task', exact: true }).click();
    await page.getByRole('dialog', { name: 'New task' }).getByLabel('Task', { exact: true }).fill('New shared task');
    await page.getByRole('button', { name: 'Save task' }).click();
    await expect(page.getByLabel('Complete New shared task')).toBeVisible();
    await mainNavigation(page).getByRole('button', { name: 'Home', exact: true }).click();
    await page.getByRole('button', { name: 'Add shopping item', exact: true }).click();
    await page.getByRole('button', { name: '+ Custom item' }).click();
    await page.getByLabel('Custom product').fill('Home test item');
    await page.locator('.quick-custom').getByRole('button', { name: 'Add', exact: true }).click();
    await page.getByRole('button', { name: 'Add 1 item' }).click();
    await expect(sections.nth(1)).toContainText('1 item');
    await expect(page.getByRole('checkbox', { name: 'Mark Home test item as purchased' })).toBeVisible();
    await page.getByRole('button', { name: 'Plan dinner', exact: true }).click();
    await page.getByLabel('Saved recipe').selectOption({ label: 'Dinner pasta' });
    await page.getByRole('button', { name: 'Save meal' }).click();
    await mainNavigation(page).getByRole('button', { name: 'Home', exact: true }).click();
    await expect(page.getByRole('button', { name: /Tonight’s dinner/ })).toContainText('Dinner pasta');
    await page.getByRole('button', { name: 'Plan dinner', exact: true }).click();
    await expect(page.getByRole('dialog', { name: 'Edit dinner' }).getByLabel('Saved recipe').locator('option:checked')).toHaveText('Dinner pasta');
    await page.getByRole('dialog', { name: 'Edit dinner' }).getByRole('button', { name: 'Close' }).click();
    await mainNavigation(page).getByRole('button', { name: 'Home', exact: true }).click();
    await page.getByRole('button', { name: /Tonight’s dinner/ }).click();
    await expect(page.locator('.recipe-detail')).toContainText('Cook pasta.');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await context.close();
  }
});
