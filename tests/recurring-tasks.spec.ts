import { expect, test } from '@playwright/test';
import { mainNavigation } from './navigation';
import { pocPassword, transport } from './helpers/sharedTransport';

test.use({ serviceWorkers: 'block', viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true });

test('recurring tasks keep history, assignment and notes, and can be stopped', async ({ page, context, browser }) => {
  const server = transport(); await server.attach(context);
  await page.goto('./'); await page.getByRole('button', { name: 'Masha', exact: true }).click();
  await page.getByLabel('Password', { exact: true }).fill(pocPassword); await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.locator('.task-dashboard').getByRole('button', { name: 'View all' }).click();
  await expect(page.getByText('Little things bring us closer.')).toHaveCount(0);
  await page.getByRole('button', { name: '+ Add task' }).click();
  const editor = page.getByRole('dialog', { name: 'New task' });
  await editor.getByLabel('Task', { exact: true }).fill('Weekly recycling');
  await editor.getByRole('combobox', { name: 'Repeat', exact: true }).selectOption('weekdays');
  await expect(editor.getByRole('button', { name: 'Save task' })).toBeDisabled();
  await editor.getByLabel('Monday', { exact: true }).check();
  await editor.getByLabel('Thursday', { exact: true }).check();
  await editor.getByLabel('Assign to').selectOption('damian');
  await editor.getByLabel('Due date (optional)').fill('2026-11-16');
  await editor.getByLabel('Priority').selectOption('high');
  await editor.getByLabel('Notes (optional)').fill('Take the blue bags');
  await editor.getByRole('combobox', { name: 'Repeat', exact: true }).selectOption('weekly');
  await page.evaluate(() => { const viewport = window.visualViewport!; Object.defineProperty(viewport, 'height', { value: 460, configurable: true }); viewport.dispatchEvent(new Event('resize')); });
  await expect.poll(async () => (await editor.boundingBox())!.y + (await editor.boundingBox())!.height).toBeLessThanOrEqual(460);
  await editor.getByRole('button', { name: 'Save task' }).scrollIntoViewIfNeeded();
  await expect(editor.getByRole('button', { name: 'Save task' })).toBeInViewport();
  await page.evaluate(() => { const viewport = window.visualViewport!; delete (viewport as unknown as { height?: number }).height; viewport.dispatchEvent(new Event('resize')); });
  await editor.getByRole('button', { name: 'Save task' }).click();
  const task = page.locator('.task-row').filter({ hasText: 'Weekly recycling' });
  await expect(task).toContainText('Weekly'); await expect(task).toContainText('Damian');
  const partnerContext = await browser.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
  await server.attach(partnerContext);
  const partner = await partnerContext.newPage();
  await partner.goto('./'); await partner.getByRole('button', { name: 'Damian', exact: true }).click();
  await partner.getByLabel('Password', { exact: true }).fill(pocPassword); await partner.getByRole('button', { name: 'Sign in', exact: true }).click();
  await partner.locator('.task-dashboard').getByRole('button', { name: 'View all' }).click();
  await expect(partner.locator('.task-row').filter({ hasText: 'Weekly recycling' })).toContainText('Weekly');
  await partner.getByLabel('Complete Weekly recycling').click();
  await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')));
  await expect(task).toHaveCount(1); await expect(task).toContainText('23 Nov');
  await task.locator('.task-main').click();
  const edit = page.getByRole('dialog', { name: 'Edit task' });
  await expect(edit.getByLabel('Notes (optional)')).toHaveValue('Take the blue bags');
  await expect(edit.getByLabel('Assign to')).toHaveValue('damian');
  await expect(edit.getByLabel('Priority')).toHaveValue('high');
  await edit.getByRole('combobox', { name: 'Repeat', exact: true }).selectOption('never');
  await edit.getByRole('button', { name: 'Save task' }).click();
  await expect(task.locator('.badge-repeat')).toHaveCount(0);
  await page.getByLabel('Complete Weekly recycling').click();
  await expect(page.locator('.task-row').filter({ hasText: 'Weekly recycling' })).toHaveCount(0);
  await page.getByRole('button', { name: /^Completed/ }).click();
  await expect(page.locator('.task-row').filter({ hasText: 'Weekly recycling' })).toHaveCount(2);
  await mainNavigation(page).getByRole('button', { name: 'Home', exact: true }).click();
  await expect(page.locator('.task-dashboard')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await partnerContext.close();
});
